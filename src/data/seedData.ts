export function buildInitialDirectoryEntries(): StakeDirectoryEntry[] {
  const entries: StakeDirectoryEntry[] = [];
  for (const orgDef of STAKE_ORG_STRUCTURE) {
    for (const slot of orgDef.fixedSlots) {
      const profileId = SEED_SLOT_PROFILE_MAP[slot.slot_key];
      const matched = profileId ? DEV_PROFILES.find((p) => p.id === profileId) : undefined;
      const scExtra = orgDef.code === 'SUMO_CONSEJO' ? SEED_SUMO_CONSEJO_DEFAULTS[slot.slot_key] : undefined;

      entries.push({
        id: `dir-${slot.slot_key}`,
        directory_org: orgDef.code as DirectoryOrgCode,
        slot_key: slot.slot_key,
        calling: slot.calling,
        is_fixed_slot: true,
        first_name: matched?.first_name || '',
        last_name: matched?.last_name || '',
        phone: matched?.phone ? normalizeUruguayanMobile(matched.phone) : '',
        email: matched?.email || '',
        has_app_access: matched ? matched.is_active : false,
        role: matched ? matched.role : slot.defaultRole,
        can_approve_activities: matched ? matched.can_approve_activities : Boolean(slot.defaultCanApprove),
        is_permanent_admin: matched ? matched.is_permanent_admin : Boolean(slot.isPermanentAdmin),
        assigned_unit: scExtra?.unit || '',
        assigned_org_notes: scExtra?.notes || '',
      });
    }
  }
  return entries;
}

